from __future__ import annotations

from dataclasses import dataclass
from typing import Optional


@dataclass(frozen=True, slots=True)
class ColumnSpec:
    """One column of a metric schema; serializes to {key, type, label}."""

    key: str
    type: str  # date | int | float | string | datetime
    label: str


@dataclass(frozen=True, slots=True)
class QueryOptions:
    """Optional ORDER BY / LIMIT for a metric query (sparse)."""

    order_by: Optional[str] = None
    limit: Optional[int] = None


@dataclass(frozen=True, slots=True)
class MetricSpec:
    """All metadata for one metric, collapsed from the legacy 9 dicts."""

    name: str
    table: str
    schema: tuple[ColumnSpec, ...]
    domain: str
    label: str
    description: str
    chart_hint: str = "table"
    date_col: Optional[str] = None  # None = cross-section snapshot
    kb_col: Optional[str] = None  # None = global metric
    query_options: Optional[QueryOptions] = None


