export function normalizeAutomationLocale(
  locale?: string | null,
): AutomationUiLocale {
  if (!locale) return "zh-CN";
  return locale?.toLowerCase().startsWith("zh") ? "zh-CN" : "en";
}

function interpolate(
  message: string,
  values: AutomationMessageValues = {},
): string {
  return message.replace(/\{\{(\w+)\}\}/g, (_, key: string) =>
    String(values[key] ?? ""),
  );
}

export function translateAutomationMessage(
  locale: AutomationUiLocale,
  key: string,
  values?: AutomationMessageValues,
): string {
  const sharedKey = automationLegacyMessageAliases[key] ?? key;
  const message =
    automationMessages[locale][
      sharedKey as keyof (typeof automationMessages)[typeof locale]
    ] ?? automationMessages.en[sharedKey as keyof typeof automationMessages.en];
  return message ? interpolate(message, values) : key;
}
