import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { join } from 'node:path'
import { test } from 'vitest'

import {
  ARTIFACT_DECLARATION_CALL_ID,
  artifactDeclarationCommand,
  assertArtifactDeclarationOutput,
} from '../e2e/desktop/modules/device-artifact-declaration-fixture.mjs'

const CONTENT = '# Artifact "quoted"\n单引号 \'、反引号 `、美元 $HOME 与 & 都是内容。\n'
const MARKER = '[WEGENT_ARTIFACT]'
const artifact = () => ({
  id: 7,
  name: 'report.md',
  relative_path: 'report.md',
  file_size: Buffer.byteLength(CONTENT),
  sha256: createHash('sha256').update(CONTENT).digest('hex'),
  download_url: '/api/tasks/42/remote-workspace/artifacts/7/file',
})
const outputRequest = (output, type = 'function_call_output') => ({
  input: [{ type, call_id: ARTIFACT_DECLARATION_CALL_ID, output }],
})

test.each(['function_call_output', 'custom_tool_call_output'])(
  'verifies the actual declaration metadata in %s',
  type => {
    const output = `${MARKER}${JSON.stringify(artifact())}\n`

    assert.deepEqual(
      assertArtifactDeclarationOutput(outputRequest(output, type), CONTENT),
      artifact()
    )
  }
)

test.each(['array', 'JSON string'])(
  'decodes the real programmatic input_text wire payload represented as %s',
  representation => {
    const content = '# Desktop artifact\nGenerated by the real associated Codex Task.\n'
    const declared = {
      id: 1,
      task_id: 1,
      subtask_id: 2,
      relative_path: 'report.md',
      name: 'report.md',
      file_size: 64,
      mime_type: 'text/plain',
      modified_at: 1793164754,
      sha256: 'e7a44aac80ec38c5e07ae5ce341b4bbee15e2b07593aa3a3d67a96947893fcf4',
      download_url: '/api/tasks/1/remote-workspace/artifacts/1/file',
    }
    const blocks = [
      { type: 'input_text', text: 'Script completed\nWall time 0.2 seconds\nOutput:\n' },
      { type: 'input_text', text: `${MARKER}${JSON.stringify(declared)}\n` },
    ]
    const output = representation === 'array' ? blocks : JSON.stringify(blocks)

    assert.deepEqual(
      assertArtifactDeclarationOutput(outputRequest(output, 'custom_tool_call_output'), content),
      declared
    )
  }
)

test.each([
  '[{"type":"input_text",}]',
  [{ type: 'input_text', text: 42 }],
  [{ type: 'input_text' }],
  [{ type: 'output_text', text: `${MARKER}${JSON.stringify(artifact())}` }],
  [{ type: 'input_text', text: `${MARKER}${JSON.stringify(artifact())}` }, null],
])('rejects malformed or unsupported programmatic text blocks: %j', output => {
  assert.throws(() =>
    assertArtifactDeclarationOutput(outputRequest(output, 'custom_tool_call_output'), CONTENT)
  )
})

test('text-block decoding cannot borrow a declaration from a different call', () => {
  const blocks = [{ type: 'input_text', text: `${MARKER}${JSON.stringify(artifact())}\n` }]
  const request = {
    input: [
      { type: 'custom_tool_call_output', call_id: 'another-tool', output: blocks },
      {
        type: 'custom_tool_call_output',
        call_id: ARTIFACT_DECLARATION_CALL_ID,
        output: [{ type: 'input_text', text: 'report.md declaration failed' }],
      },
    ],
  }

  assert.throws(() => assertArtifactDeclarationOutput(request, CONTENT), /Expected one successful/)
})

test('text-block decoding preserves nonzero exit metadata before a declaration', () => {
  const blocks = [
    { type: 'input_text', text: 'Process exited with code 23\nOutput:\n' },
    { type: 'input_text', text: `${MARKER}${JSON.stringify(artifact())}\n` },
  ]

  assert.throws(
    () =>
      assertArtifactDeclarationOutput(outputRequest(blocks, 'custom_tool_call_output'), CONTENT),
    /declaration tool failed/
  )
})

test.each([
  'Cannot declare report.md: permission denied',
  'Process exited with code 1\nFinal output:\nreport.md was not generated',
  'Session ID: 123\nreport.md declaration is still running',
])('rejects unsuccessful tool output even when it mentions report.md: %s', output => {
  assert.throws(() => assertArtifactDeclarationOutput(outputRequest(output), CONTENT))
})

test('does not mistake echoed commands or another tool result for the declaration', () => {
  const successful = `${MARKER}${JSON.stringify(artifact())}\n`
  const request = {
    input: [
      { type: 'function_call', call_id: ARTIFACT_DECLARATION_CALL_ID, arguments: successful },
      { type: 'function_call_output', call_id: 'another-tool', output: successful },
      { role: 'user', content: 'report.md' },
    ],
  }

  assert.throws(() => assertArtifactDeclarationOutput(request, CONTENT), /did not return output/)
})

test('rejects a failed process even when its output contains a declaration marker', () => {
  const output = `Process exited with code 1\nFinal output:\n${MARKER}${JSON.stringify(artifact())}`

  assert.throws(
    () => assertArtifactDeclarationOutput(outputRequest(output), CONTENT),
    /declaration tool failed/
  )
})

test.each([
  { name: 'different.md' },
  { relative_path: '../report.md' },
  { file_size: 0 },
  { sha256: 'wrong-content' },
  { download_url: '/api/tasks/42/remote-workspace/artifacts/8/file' },
])('rejects declaration metadata that does not identify the generated report: %j', patch => {
  const output = `${MARKER}${JSON.stringify({ ...artifact(), ...patch })}\n`

  assert.throws(() => assertArtifactDeclarationOutput(outputRequest(output), CONTENT))
})

test.each([0, 23])(
  'the real Node command writes exact bytes and propagates child exit %i',
  async code => {
    const root = await mkdtemp(join(tmpdir(), 'artifact-declaration-fixture-'))
    try {
      const workspace = join(root, "workspace ' & $ 北京")
      await mkdir(workspace)
      await writeFile(
        join(workspace, 'artifact'),
        `const fs = require('node:fs')
fs.writeFileSync('invocation.json', JSON.stringify(process.argv.slice(2)))
if (${code} !== 0) {
  process.stderr.write('Cannot declare report.md\\n')
  process.exit(${code})
}
process.stdout.write(${JSON.stringify(MARKER + JSON.stringify(artifact()) + '\n')})
`
      )
      const command = artifactDeclarationCommand(CONTENT)
      assert.match(command, /^node -e "eval\(Buffer\.from\('[A-Za-z0-9+/=]+','base64'\)/)
      const windows = process.platform === 'win32'
      const result = spawnSync(
        windows ? 'powershell.exe' : '/bin/sh',
        windows ? ['-NoProfile', '-NonInteractive', '-Command', command] : ['-c', command],
        {
          cwd: root,
          encoding: 'utf8',
          env: {
            ...process.env,
            WEGENT_TASK_WORKSPACE: workspace,
            WEGENT_BACKEND_TASK_ID: '42',
            WEGENT_EXECUTOR_BINARY: process.execPath,
          },
          timeout: 5_000,
        }
      )

      assert.equal(result.error, undefined)
      assert.equal(result.status, code, result.stderr)
      assert.equal(await readFile(join(workspace, 'report.md'), 'utf8'), CONTENT)
      assert.deepEqual(JSON.parse(await readFile(join(workspace, 'invocation.json'), 'utf8')), [
        'declare',
        '--path',
        'report.md',
      ])
      if (code === 0) {
        assert.deepEqual(
          assertArtifactDeclarationOutput(outputRequest(result.stdout), CONTENT),
          artifact()
        )
      } else {
        assert.throws(() => assertArtifactDeclarationOutput(outputRequest(result.stderr), CONTENT))
      }
    } finally {
      await rm(root, { recursive: true, force: true })
    }
  }
)
