import assert from 'node:assert/strict'

import { CLOUD_DEVICE_ID, createSingleRootLocalProject } from '../modules/shared.mjs'
import {
  ARTIFACT_DECLARATION_CALL_ID,
  artifactDeclarationCommand,
  assertArtifactDeclarationOutput,
} from '../modules/device-artifact-declaration-fixture.mjs'
import {
  assistantMessage,
  codexRequestKind,
  createSse,
  customToolCall,
  functionCall,
  readRequestBody,
  requestContainsToolOutput,
  requestAdvertisesProgrammaticExec,
  responseCompleted,
  responseCreated,
  selectShellToolCommand,
  selectProgrammaticExec,
} from '../modules/response-protocol.mjs'

const PROMPT = 'WEWORK_ASSOCIATED_TASK_ARTIFACT_DECLARATION'
const CONTENT = '# Desktop artifact\nGenerated by the real associated Codex Task.\n'
const COMPLETE = 'DESKTOP_ARTIFACT_DECLARED'

export function createDesktopScenario({ captureScreenshot, workbenchReadyTimeoutMs, uiTimeoutMs }) {
  let cloud
  let active = false
  let toolRequested = false
  let toolVerified = false
  let declaredArtifact
  const request = async (path, method = 'GET', body) => {
    const response = await fetch(`${cloud.backendUrl}${path}`, {
      method,
      headers: {
        Authorization: `Bearer ${cloud.authToken}`,
        'Content-Type': 'application/json',
      },
      ...(body === undefined ? {} : { body: JSON.stringify(body) }),
    })
    assert.ok(response.ok, `${method} ${path}: ${response.status} ${await response.clone().text()}`)
    return response.json()
  }
  return {
    requiresCloudEnvironment: true,
    setCloudEnvironment(environment) {
      cloud = environment
    },
    async handleHttp(req, res, url) {
      if (
        !active ||
        req.method !== 'POST' ||
        !['/responses', '/v1/responses'].includes(url.pathname)
      )
        return false
      const body = await readRequestBody(req)
      if (!JSON.stringify(body).includes(PROMPT)) return false
      const responseId = `artifact-${Date.now()}`
      let events
      if (codexRequestKind(body) === 'prewarm') events = [assistantMessage('Ready')]
      else if (!requestContainsToolOutput(body, ARTIFACT_DECLARATION_CALL_ID)) {
        assert.equal(toolRequested, false, 'The artifact generation tool was requested twice')
        toolRequested = true
        const command = artifactDeclarationCommand(CONTENT)
        const shell = process.platform === 'win32' ? 'powershell.exe' : '/bin/bash'
        if (requestAdvertisesProgrammaticExec(body)) {
          const tool = selectProgrammaticExec(
            body,
            [
              `const result = await tools.exec_command(${JSON.stringify({ cmd: command, shell, login: false, workdir: cloud.runtimeWorkspaceRoot, yield_time_ms: 10000 })})`,
              'if (result.exit_code !== 0) throw new Error(JSON.stringify(result))',
              'text(result.output)',
            ].join('\n')
          )
          const event = customToolCall(ARTIFACT_DECLARATION_CALL_ID, tool.name, tool.input)
          event.item.namespace = 'functions'
          events = [event]
        } else {
          const tool = selectShellToolCommand(body, command, cloud.runtimeWorkspaceRoot, {
            yieldTimeMs: 10000,
          })
          if (tool.name === 'exec_command') Object.assign(tool.arguments, { shell, login: false })
          events = functionCall(ARTIFACT_DECLARATION_CALL_ID, tool.name, tool.arguments)
        }
      } else {
        declaredArtifact = assertArtifactDeclarationOutput(body, CONTENT)
        toolVerified = true
        events = [assistantMessage(COMPLETE)]
      }
      res.writeHead(200, { 'content-type': 'text/event-stream; charset=utf-8' })
      res.end(createSse([responseCreated(responseId), ...events, responseCompleted(responseId)]))
      return true
    },
    async verify(control) {
      await request('/api/admin/setup-complete', 'POST')
      const suffix = `desktop-artifact-${process.pid}`
      const bot = await request('/api/bots', 'POST', {
        name: `${suffix}-bot`,
        shell_name: 'Codex',
        namespace: 'default',
        agent_config: { bind_model: 'desktop-e2e-cloud-responses', bind_model_type: 'public' },
        system_prompt: 'Generate the requested deliverable and explicitly declare it.',
      })
      const team = await request('/api/teams', 'POST', {
        name: `${suffix}-team`,
        bots: [{ bot_id: bot.id, role: 'worker', bot_prompt: '' }],
        namespace: 'default',
        bind_mode: ['task'],
        requires_workspace: false,
        is_active: true,
      })
      active = true
      const task = await request('/api/device-chat/tasks', 'POST', {
        teamId: team.id,
        deviceId: CLOUD_DEVICE_ID,
        message: PROMPT,
        modelId: 'desktop-e2e-cloud-responses',
        modelType: 'public',
      })
      const deadline = Date.now() + workbenchReadyTimeoutMs
      let detail
      while (Date.now() < deadline) {
        detail = await request(`/api/tasks/${task.taskId}`)
        if (['COMPLETED', 'FAILED', 'CANCELLED'].includes(detail.status)) break
        await new Promise(resolve => setTimeout(resolve, 200))
      }
      assert.equal(detail.status, 'COMPLETED', JSON.stringify(detail))
      assert.ok(
        toolRequested && toolVerified,
        'Real Codex generation and declaration did not complete'
      )
      const contexts = detail.subtasks
        .flatMap(subtask => subtask.contexts ?? [])
        .filter(context => context.context_type === 'remote_workspace_artifact')
      assert.equal(contexts.length, 1)
      const artifact = contexts[0]
      assert.equal(artifact.id, declaredArtifact.id)
      assert.equal(artifact.name, 'report.md')
      const url = `${cloud.backendUrl}/api/tasks/${task.taskId}/remote-workspace/artifacts/${artifact.id}/file`
      const download = await fetch(url, { headers: { Authorization: `Bearer ${cloud.authToken}` } })
      assert.equal(download.status, 200)
      assert.match(download.headers.get('content-disposition'), /report\.md/)
      assert.equal(await download.text(), CONTENT)
      const rows = await cloud.queryDatabase(
        'SELECT type_data, OCTET_LENGTH(binary_data) AS bytes FROM subtask_contexts WHERE id = %s',
        [artifact.id]
      )
      assert.equal(rows[0].bytes, 0)
      const metadata = JSON.parse(rows[0].type_data)
      assert.equal(metadata.source.executor_name, `device-${CLOUD_DEVICE_ID}`)
      // Wework owns a native file viewer rather than the web chat ContextBadge.
      // Open the actual generated file through that viewer; do not invent a
      // Backend Task association for desktop runtime-only conversations.
      await createSingleRootLocalProject(
        control,
        metadata.source.workspace_root,
        suffix,
        uiTimeoutMs
      )
      const composer =
        '[data-testid="desktop-workbench-main"][data-active-workbench-pane="true"] [data-testid="chat-message-input"][contenteditable="true"]'
      await control.command('waitFor', composer, { timeoutMs: uiTimeoutMs })
      await control.command('nativePress', composer, {
        key: `${process.platform === 'darwin' ? 'Meta' : 'Control'}+Alt+F`,
      })
      await control.command('waitFor', 'button[data-type="item"][aria-label="report.md"]', {
        timeoutMs: uiTimeoutMs,
      })
      await control.command('click', 'button[data-type="item"][aria-label="report.md"]')
      await control.command('waitFor', '[data-testid="workspace-file-editor"] .cm-content', {
        text: 'Generated by the real associated Codex Task.',
        timeoutMs: uiTimeoutMs,
      })
      await captureScreenshot(control, 'device-artifact-native-preview.png', 'body')
      const reloaded = await request(`/api/tasks/${task.taskId}`)
      assert.ok(JSON.stringify(reloaded).includes('remote_workspace_artifact'))
      const repeated = await fetch(url, { headers: { Authorization: `Bearer ${cloud.authToken}` } })
      assert.equal(repeated.status, 200)
      assert.equal(await repeated.text(), CONTENT)
    },
  }
}
