import type { PaneSessionExternal, PaneSessionFrame } from './workbenchPaneSessionFrame'
import type { PaneCommands } from './workbenchPaneCommandContext'
import type { createRuntimeConversationSearchSource } from './runtimeConversationSearchSource'
export function createPaneSessionView(
  frame: PaneSessionFrame,
  commands: PaneCommands,
  search: ReturnType<typeof createRuntimeConversationSearchSource>,
  attachmentCommands: Pick<
    PaneSessionExternal['attachmentState'],
    'handleFileSelect' | 'removeAttachment' | 'dismissAttachmentError'
  >
) {
  const {
    queuedMessages,
    queuedMessagesPaused,
    guidanceMessages,
    codeCommentContexts,
    browserAnnotationCommand,
    inputScopeKey,
    attachmentState,
    draftStore,
    getInput,
    setInputForScope,
    error,
    answeredRequestUserInputIds,
    transcriptError,
    transcriptHasMoreBefore,
    transcriptBeforeCursor,
    transcriptFullContent,
    loadedTranscriptRanges,
    turnNavigation,
    goalDraftActive,
    runtimeTaskLoadTarget,
    transcriptLoading,
    transcriptLoadingMoreBefore,
    taskPlan,
    subagentStatuses,
    messages,
    turns,
    goalExecutionStatus,
    paneStatus,
    goal,
    goalContinuing,
  } = frame
  const { handleFileSelect, removeAttachment, dismissAttachmentError } = attachmentCommands
  const {
    replaceInput,
    getDraftEditVersion,
    setError,
    clearError,
    onDraftEdit,
    reloadRuntimeTranscript,
    loadMoreTranscriptBefore,
    loadTranscriptTurnNavigationItem,
    loadTranscriptGap,
    sendContinuation,
    retryFailedMessageInPane,
    editLastUserMessageInPane,
    ignoreRequestUserInput,
    sendRequestUserInputResponse,
    send,
    addCodeComment,
    replaceBrowserCodeComments,
    removeBrowserCodeComments,
    clearCodeComments,
    cancelQueuedMessage,
    forceStartQueuedMessage,
    resumeQueuedMessages,
    resumeQueuedMessagesWithInput,
    clearQueuedMessages,
    reorderQueuedMessages,
    editQueuedMessage,
    sendQueuedAsGuidance,
    interruptAndSendQueued,
    compactContext,
    setCurrentGoal,
    cancelGoalDraft,
    editCurrentGoal,
    pauseCurrentGoal,
    resumeCurrentGoal,
    pauseCurrentResponse,
    clearCurrentGoal,
    cancelGuidanceMessage,
    setInput,
  } = commands
  const conversationSearch = { ...search.commands, page: search.getSnapshot() }
  return {
    scopeKey: inputScopeKey,
    attachments: attachmentState.attachments,
    uploadingFiles: attachmentState.uploadingFiles,
    attachmentErrors: attachmentState.errors,
    dismissAttachmentError,
    handleFileSelect,
    removeAttachment,
    messages,
    turns,
    queuedMessages,
    queuedMessagesPaused,
    guidanceMessages,
    codeCommentContexts,
    browserAnnotationCommand,
    draftStore,
    getInput,
    setInputForScope,
    setInput,
    replaceInput,
    onDraftEdit,
    getDraftEditVersion,
    error,
    setError,
    clearError,
    status: paneStatus,
    sending: paneStatus.isSubmitting,
    waitingForAssistant: paneStatus.isWaitingForAssistantIndicator,
    answeredRequestUserInputIds,
    transcriptLoading,
    transcriptError,
    reloadRuntimeTranscript,
    transcriptHasMoreBefore,
    transcriptBeforeCursor,
    transcriptLoadingMoreBefore,
    transcriptFullContent,
    loadedTranscriptRanges,
    turnNavigation,
    subagentStatuses,
    goal,
    goalContinuing,
    goalExecutionStatus,
    taskPlan,
    goalDraftActive,
    loadMoreTranscriptBefore,
    loadTranscriptTurnNavigationItem,
    loadTranscriptGap,
    searchTranscript: runtimeTaskLoadTarget ? conversationSearch.search : undefined,
    ensureSearchMatch: runtimeTaskLoadTarget ? conversationSearch.ensureMatch : undefined,
    searchPage: conversationSearch.page,
    loadSearchContext: conversationSearch.loadMoreContext,
    releaseSearchPage: conversationSearch.releasePage,
    send,
    sendContinuation,
    retryFailedMessage: retryFailedMessageInPane,
    editLastUserMessage: editLastUserMessageInPane,
    sendRequestUserInputResponse,
    ignoreRequestUserInput,
    addCodeComment,
    replaceBrowserCodeComments,
    removeBrowserCodeComments,
    clearCodeComments,
    cancelQueuedMessage,
    forceStartQueuedMessage,
    resumeQueuedMessages,
    resumeQueuedMessagesWithInput,
    clearQueuedMessages,
    reorderQueuedMessages,
    sendQueuedAsGuidance,
    interruptAndSendQueued,
    editQueuedMessage,
    cancelGuidanceMessage,
    pauseCurrentResponse,
    compactContext,
    setCurrentGoal,
    cancelGoalDraft,
    editCurrentGoal,
    pauseCurrentGoal,
    resumeCurrentGoal,
    clearCurrentGoal,
  }
}
