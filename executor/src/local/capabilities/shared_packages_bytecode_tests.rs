use super::*;

fn python_packages(executable_script: bool) -> Packages {
    let mut bytes = packages("v1");
    let mut writer = zip::ZipWriter::new(Cursor::new(Vec::new()));
    for (path, text) in [
        (
            ".claude-plugin/plugin.json",
            "{\"name\":\"demo\",\"version\":\"1.0\"}",
        ),
        ("scripts/provider.py", "print('original')"),
        ("scripts/__pycache__/canonical.pyc", "packaged cache"),
        ("scripts/precompiled.pyc", "packaged resource"),
        ("hooks/run.sh", "#!/bin/sh\nexit 0\n"),
    ] {
        let mode = if executable_script && path == "scripts/provider.py" {
            0o755
        } else {
            0o644
        };
        writer
            .start_file(
                path,
                zip::write::FileOptions::default().unix_permissions(mode),
            )
            .unwrap();
        writer.write_all(text.as_bytes()).unwrap();
    }
    bytes.plugin = writer.finish().unwrap().into_inner();
    bytes
}

fn python_payload(bytes: &Packages) -> Value {
    json!({"scope":"plugins", "plugins":[{"name":"demo",
        "installed_plugin_id":1,"marketplace":"wegent","version":"1.0",
        "download_path":"/package","checksum":sha256_digest(&bytes.plugin)}]})
}

async fn sync_changes_runtime(
    handler: &CapabilitySyncHandler<Packages>,
    store: &GlobalCapabilityStore,
    payload: &Value,
    spec: &PluginSyncSpec,
) -> bool {
    let before = ActivationRevision::new(
        store,
        &store.manifest.load().unwrap(),
        &[],
        std::iter::once(spec),
        false,
        true,
    );
    let result = handler.apply_sync(payload.clone()).await.unwrap();
    let changed = before.has_changed();
    let _activation = crate::services::capability_activation::activate().await;
    drop(before);
    assert_eq!(result["success"], true);
    changed
}

#[tokio::test]
async fn unchanged_python_plugin_sync_ignores_only_runtime_generated_bytecode() {
    let root = tempfile::tempdir().unwrap();
    let store = store(root.path());
    let bytes = python_packages(false);
    let payload = python_payload(&bytes);
    let handler = CapabilitySyncHandler::with_package_provider("", store.clone(), bytes);
    assert_eq!(
        handler.apply_sync(payload.clone()).await.unwrap()["success"],
        true
    );
    let spec = PluginSyncSpec::from_value(&payload["plugins"][0]).unwrap();
    let runtimes = store.plugin_runtime_targets(&spec);
    for (runtime, _) in &runtimes {
        fs::write(
            runtime.join("scripts/__pycache__/provider.cpython-312.pyc"),
            "generated",
        )
        .unwrap();
    }

    assert!(
        !sync_changes_runtime(&handler, &store, &payload, &spec).await,
        "removing runtime-generated bytecode must not reload an unchanged capability"
    );

    for (relative, replacement, expected) in [
        ("scripts/__pycache__/canonical.pyc", None, "packaged cache"),
        (
            "scripts/__pycache__/canonical.pyc",
            Some("changed"),
            "packaged cache",
        ),
        (
            "scripts/precompiled.pyc",
            Some("changed"),
            "packaged resource",
        ),
        (
            "scripts/provider.py",
            Some("print('changed')"),
            "print('original')",
        ),
    ] {
        for (runtime, _) in &runtimes {
            let path = runtime.join(relative);
            if let Some(replacement) = replacement {
                fs::write(path, replacement).unwrap();
            } else {
                fs::remove_file(path).unwrap();
            }
        }
        assert!(sync_changes_runtime(&handler, &store, &payload, &spec).await);
        for (runtime, _) in &runtimes {
            assert_eq!(
                fs::read_to_string(runtime.join(relative)).unwrap(),
                expected
            );
        }
    }
    assert!(!sync_changes_runtime(&handler, &store, &payload, &spec).await);
}

#[tokio::test]
async fn python_plugin_reuses_each_runtime_and_marketplace_copy_independently() {
    let root = tempfile::tempdir().unwrap();
    let store = store(root.path());
    let bytes = python_packages(false);
    let mut payload = python_payload(&bytes);
    let handler = CapabilitySyncHandler::with_package_provider("", store.clone(), bytes);
    handler.apply_sync(payload.clone()).await.unwrap();
    let spec = PluginSyncSpec::from_value(&payload["plugins"][0]).unwrap();
    let codex = store.plugin_codex_link(&spec);
    let claude = store.plugin_runtime_link(&spec);
    let generated = "scripts/__pycache__/generated.pyc";
    fs::write(claude.join(generated), "runtime cache").unwrap();
    fs::write(codex.join("scripts/provider.py"), "drift").unwrap();
    assert!(sync_changes_runtime(&handler, &store, &payload, &spec).await);
    assert!(claude.join(generated).is_file());
    assert_eq!(
        fs::read_to_string(codex.join("scripts/provider.py")).unwrap(),
        "print('original')"
    );

    let mut marketplaces = Vec::new();
    for (runtime, field) in store.plugin_runtime_targets(&spec) {
        let is_claude = field == "claude_link";
        let marketplace = if is_claude {
            store.claude_marketplace_dir(&spec.marketplace)
        } else {
            store.codex_marketplace_dir(&spec.marketplace)
        }
        .join("plugins")
        .join(store.marketplace_plugin_name(&spec, is_claude));
        remove_existing_path(&marketplace).unwrap();
        copy_dir_recursive(&runtime, &marketplace).unwrap();
        fs::write(marketplace.join(generated), "marketplace cache").unwrap();
        marketplaces.push(marketplace);
    }
    assert!(!sync_changes_runtime(&handler, &store, &payload, &spec).await);
    for marketplace in &marketplaces {
        assert!(!marketplace.is_symlink());
        assert_eq!(
            fs::read_to_string(marketplace.join(generated)).unwrap(),
            "marketplace cache"
        );
    }

    payload["plugins"][0]["enabled"] = json!(false);
    payload["plugins"][0]["component_states"] = json!({"skills/demo":false});
    assert!(sync_changes_runtime(&handler, &store, &payload, &spec).await);
    let config = fs::read_to_string(root.path().join("codex/config.toml"))
        .unwrap()
        .parse::<DocumentMut>()
        .unwrap();
    assert_eq!(
        config["plugins"]["demo@wegent"]["enabled"].as_bool(),
        Some(false)
    );
    assert_eq!(
        store.manifest.load().unwrap()["plugins"]["demo@wegent"]["component_states"],
        json!({"skills/demo":false})
    );
    assert!(claude.join(generated).is_file());

    for marketplace in &marketplaces {
        fs::remove_file(marketplace.join("scripts/__pycache__/canonical.pyc")).unwrap();
    }
    let before = ActivationRevision::new(
        &store,
        &store.manifest.load().unwrap(),
        &[],
        std::iter::once(&spec),
        false,
        true,
    );
    let rejected = handler.apply_sync(payload).await.unwrap();
    let changed = before.has_changed();
    {
        let _activation = crate::services::capability_activation::activate().await;
        drop(before);
    }
    assert_eq!(rejected["success"], false);
    assert!(rejected["plugins"][0]["error"]
        .as_str()
        .unwrap()
        .contains("occupied by an unrelated source"));
    assert!(
        !changed,
        "a changed marketplace copy must retain its existing ownership protection"
    );
    for marketplace in &marketplaces {
        assert!(!marketplace.is_symlink());
        assert!(!marketplace
            .join("scripts/__pycache__/canonical.pyc")
            .exists());
        assert_eq!(
            fs::read_to_string(marketplace.join(generated)).unwrap(),
            "marketplace cache"
        );
    }
}

#[cfg(unix)]
#[tokio::test]
async fn python_plugin_mode_drift_repairs_with_existing_rollback_and_source_modes() {
    use std::os::unix::fs::PermissionsExt;

    let root = tempfile::tempdir().unwrap();
    let store = store(root.path());
    let bytes = python_packages(false);
    let payload = python_payload(&bytes);
    let handler = CapabilitySyncHandler::with_package_provider("", store.clone(), bytes);
    handler.apply_sync(payload.clone()).await.unwrap();
    let spec = PluginSyncSpec::from_value(&payload["plugins"][0]).unwrap();
    let codex = store.plugin_codex_link(&spec);
    let hook = codex.join("hooks/run.sh");
    fs::set_permissions(&hook, fs::Permissions::from_mode(0o644)).unwrap();
    let config = root.path().join("codex/config.toml");
    let valid = fs::read(&config).unwrap();
    fs::write(&config, "[invalid").unwrap();
    assert_eq!(
        handler.apply_sync(payload.clone()).await.unwrap()["success"],
        false
    );
    assert_eq!(fs::metadata(&hook).unwrap().permissions().mode() & 0o111, 0);
    fs::write(&config, valid).unwrap();
    assert!(sync_changes_runtime(&handler, &store, &payload, &spec).await);
    assert_eq!(
        fs::metadata(&hook).unwrap().permissions().mode() & 0o111,
        0o111
    );

    for (runtime, _) in store.plugin_runtime_targets(&spec) {
        fs::set_permissions(
            runtime.join("scripts/provider.py"),
            fs::Permissions::from_mode(0o755),
        )
        .unwrap();
    }
    assert!(sync_changes_runtime(&handler, &store, &payload, &spec).await);
    for (runtime, _) in store.plugin_runtime_targets(&spec) {
        assert_eq!(
            fs::metadata(runtime.join("scripts/provider.py"))
                .unwrap()
                .permissions()
                .mode()
                & 0o111,
            0
        );
    }

    let bytes = python_packages(true);
    let payload = python_payload(&bytes);
    let spec = PluginSyncSpec::from_value(&payload["plugins"][0]).unwrap();
    let handler = CapabilitySyncHandler::with_package_provider("", store.clone(), bytes);
    assert!(sync_changes_runtime(&handler, &store, &payload, &spec).await);
    for (runtime, _) in store.plugin_runtime_targets(&spec) {
        assert_eq!(
            fs::metadata(runtime.join("scripts/provider.py"))
                .unwrap()
                .permissions()
                .mode()
                & 0o111,
            0o111
        );
    }
}

#[cfg(unix)]
#[tokio::test]
async fn python_plugin_repairs_owned_nested_symlink_instead_of_reusing_it() {
    let root = tempfile::tempdir().unwrap();
    let store = store(root.path());
    let bytes = python_packages(false);
    let payload = python_payload(&bytes);
    let handler = CapabilitySyncHandler::with_package_provider("", store.clone(), bytes);
    handler.apply_sync(payload.clone()).await.unwrap();
    let spec = PluginSyncSpec::from_value(&payload["plugins"][0]).unwrap();
    let path = store.plugin_codex_link(&spec).join("scripts/provider.py");
    fs::remove_file(&path).unwrap();
    std::os::unix::fs::symlink(root.path().join("unused"), &path).unwrap();
    assert!(sync_changes_runtime(&handler, &store, &payload, &spec).await);
    assert!(!path.is_symlink());
    assert_eq!(fs::read_to_string(path).unwrap(), "print('original')");
}
