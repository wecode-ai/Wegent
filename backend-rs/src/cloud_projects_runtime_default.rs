//! `GET /api/v1/cloud-projects/{project_id}/runtime-default` — read the
//! current user's default Runtime profile binding for one cloud project.
//!
//! Mirrors `app.api.endpoints.runtime_profiles.get_project_runtime_default`
//! -> `runtime_profile_service.get_project_default(db, project_id,
//! current_user.id)`.
//!
//! Source pipeline:
//! 1. `security.get_current_user` — JWT session decode plus the labeled
//!    `users` lookup (the full twelve-column `users_<column>` projection);
//! 2. `require_cloud_project_role(db, project_id, user_id, Viewer)` — the
//!    shared `project_access_query` point form resolves the active project
//!    row and the caller's effective role in one statement;
//! 3. `runtime_profile_service._default_binding`: the active `loop_items`
//!    `runtime_binding` row for the project and user, newest `updated_at`
//!    first;
//! 4. the response returns the project id, user id, and the binding's
//!    `parent_id` (the Runtime profile id) or `null` when no binding exists.
use brz_http_server::StatusCode;
use brz_mysql::{FromMysqlRow, Mysql, MysqlResult};
use serde::Serialize;

use crate::auth::SessionUser;
use crate::board_snapshot::repository::{BoardSnapshotRepository, has_permission};
use crate::http_compat::FastApiError;
use crate::state::AppState;

/// `ProjectRuntimeDefaultView` (`app.schemas.runtime_profile`). Field names
/// are the camelCase aliases generated by `ProjectChatSchema`.
#[derive(Debug, Serialize)]
struct ProjectRuntimeDefaultView {
    #[serde(rename = "projectId")]
    project_id: String,
    #[serde(rename = "userId")]
    user_id: i32,
    #[serde(rename = "runtimeProfileId")]
    runtime_profile_id: Option<String>,
}

/// The active `loop_items` `runtime_binding` row for one project and user.
///
/// The projection re-declares the full labeled `LOOP_ITEMS_COLUMNS` so the
/// prepared statement matches the recorded exchange for replay; only the
/// `parent_id` column feeds the response.
#[derive(Debug, FromMysqlRow)]
struct RuntimeBindingRow {
    #[mysql(rename = "loop_items_parent_id")]
    parent_id: Option<String>,
}

/// The recorded `_default_binding` statement, matching the source SQLAlchemy
/// `db.query(RuntimeBinding)` filter list:
/// `cloud_project_id`, `user_id`, `is_default`, `status`, unset `deleted_at`,
/// ordered by `updated_at DESC`, `LIMIT 1`.
